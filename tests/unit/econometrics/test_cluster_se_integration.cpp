// -----------------------------------------------------------------------------
// TEST 6: 双向聚类对角元素 (方差) vs R baseline SE
// 验证标准误 (sqrt(var)) 与 R 一致
// -----------------------------------------------------------------------------
TEST_F(GrunfeldClusterSEIntegrationTest, TwoWayStandardErrors_MatchR) {
    const MatrixXD V = compute_cluster_vcov(gf.X, gf.residuals, gf.XtX_inv,
                                              gf.firm_id, true, gf.year_id);
    // R SE: [19.716680683803034, 0.016395149450111585, 0.079543189287480331]
    const Real r_se[3] = {
        std::sqrt(r_baseline::V_TWOWAY[0]),  // sqrt(V(0,0))
        std::sqrt(r_baseline::V_TWOWAY[4]),  // sqrt(V(1,1))
        std::sqrt(r_baseline::V_TWOWAY[8])   // sqrt(V(2,2))
    };
    for (Size i = 0; i < 3; ++i) {
        const Real cxx_se = std::sqrt(V(i, i));
        EXPECT_NEAR(cxx_se, r_se[i], r_baseline::TOL)
            << "SE[" << i << "] mismatch (C++=" << cxx_se << ", R=" << r_se[i] << ")";
    }
}

// -----------------------------------------------------------------------------
// TEST 7: 小样本调整系数验证 (审计)
// adj_firm = (G_firm/(G_firm-1)) * ((N-1)/(N-K)) = (10/9) * (199/197)
// adj_year = (G_year/(G_year-1)) * ((N-1)/(N-K)) = (20/19) * (199/197)
// -----------------------------------------------------------------------------
TEST_F(GrunfeldClusterSEIntegrationTest, SmallSampleAdjustment_Correct) {
    const Real adj_firm_expected = static_cast<Real>(r_baseline::G_FIRM) /
                                    static_cast<Real>(r_baseline::G_FIRM - 1) *
                                    static_cast<Real>(r_baseline::N_OBS - 1) /
                                    static_cast<Real>(r_baseline::N_OBS - r_baseline::K_COEF);
    EXPECT_NEAR(adj_firm_expected, r_baseline::ADJ_FIRM, 1e-12);

    const Real adj_year_expected = static_cast<Real>(r_baseline::G_YEAR) /
                                    static_cast<Real>(r_baseline::G_YEAR - 1) *
                                    static_cast<Real>(r_baseline::N_OBS - 1) /
                                    static_cast<Real>(r_baseline::N_OBS - r_baseline::K_COEF);
    EXPECT_NEAR(adj_year_expected, r_baseline::ADJ_YEAR, 1e-12);
}

