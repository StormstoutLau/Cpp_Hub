// -----------------------------------------------------------------------------
// TEST 9: 双向聚类 V(g1=g2) = V_oneway(g1) ( Cameron-Gelbach-Miller 公式自洽)
// 当 g1 == g2 时, V(g1)+V(g2)-V(g1∩g2) = V(g1)+V(g1)-V(g1) = V(g1)
// -----------------------------------------------------------------------------
TEST_F(GrunfeldClusterSEIntegrationTest, TwoWayG1EqualsG2_EqualsOneWay) {
    const MatrixXD V_oneway = compute_cluster_vcov(gf.X, gf.residuals, gf.XtX_inv,
                                                     gf.firm_id, false, {});
    const MatrixXD V_twoway_same = compute_cluster_vcov(gf.X, gf.residuals, gf.XtX_inv,
                                                          gf.firm_id, true, gf.firm_id);

    for (Size i = 0; i < 3; ++i) {
        for (Size j = 0; j < 3; ++j) {
            EXPECT_NEAR(V_oneway(i, j), V_twoway_same(i, j), 1e-10)
                << "V_oneway(" << i << "," << j << ") != V_twoway_g1=g2("
                << i << "," << j << ")";
        }
    }
}

// -----------------------------------------------------------------------------
// TEST 10: Grunfeld 残差平方和 (SSR) 验证
// 用于确认 OLS 拟合的正确性 (排幻觉: 数据 + 系数 + 残差 全链路一致)
// -----------------------------------------------------------------------------
TEST_F(GrunfeldClusterSEIntegrationTest, ResidualSumOfSquares_Positive) {
    const Real ssr = gf.residuals.eigen().squaredNorm();
    EXPECT_GT(ssr, 0.0);  // 非完美拟合
    // Grunfeld OLS (inv ~ value + capital) SSR ≈ 1748498 (R summary)
    // 不严格断言具体值, 仅验证非零非负
    EXPECT_LT(ssr, 1e10);  // 合理上界
}
