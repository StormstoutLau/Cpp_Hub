//   - Cameron-Gelbach-Miller (2011) REStat - 双向聚类 V_twoway = V(g1)+V(g2)-V(g1∩g2)
//   - R sandwich 3.1-3 vcovCL type="HC1" (含小样本调整 G/(G-1)*(N-1)/(N-K))
