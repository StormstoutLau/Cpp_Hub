// -----------------------------------------------------------------------------
// TEST 3: 单向聚类 (firm) vs R vcovCL(cluster=~firm, type="HC1")
// 排幻觉点 E6: 小样本调整 G/(G-1)*(N-1)/(N-K) = (10/9)*(199/197) ≈ 1.1224
