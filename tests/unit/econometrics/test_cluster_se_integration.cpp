class GrunfeldClusterSEIntegrationTest : public ::testing::Test {
protected:
    GrunfeldFixture gf;
};

// -----------------------------------------------------------------------------
// TEST 1: 数据加载正确性 (N=200, K=3, G_firm=10, G_year=20)
// 排幻觉点 I4: 验证数据完整性, 避免 R/C++ 数据不一致
// -----------------------------------------------------------------------------
TEST_F(GrunfeldClusterSEIntegrationTest, DataIntegrity) {
    EXPECT_EQ(gf.X.rows(), r_baseline::N_OBS);
    EXPECT_EQ(gf.X.cols(), r_baseline::K_COEF);
    EXPECT_EQ(gf.y.size(), r_baseline::N_OBS);

    // cluster counts
    std::unordered_map<Index, Index> firm_unique, year_unique;
    for (Index id : gf.firm_id) firm_unique[id] = 1;
    for (Index id : gf.year_id) year_unique[id] = 1;
    EXPECT_EQ(firm_unique.size(), static_cast<size_t>(r_baseline::G_FIRM));
    EXPECT_EQ(year_unique.size(), static_cast<size_t>(r_baseline::G_YEAR));

    // 首行数据核对 (Grunfeld firm=1, year=1935, inv=317.6, value=3078.5, capital=2.8)
    EXPECT_NEAR(gf.X(0, 0), 1.0, 1e-12);        // intercept
    EXPECT_NEAR(gf.X(0, 1), 3078.5, 1e-8);       // value
    EXPECT_NEAR(gf.X(0, 2), 2.8, 1e-8);          // capital
    EXPECT_NEAR(gf.y(0), 317.6, 1e-8);           // inv
    EXPECT_EQ(gf.firm_id[0], 0);                  // 0-based firm
    EXPECT_EQ(gf.year_id[0], 0);                  // 0-based year (1935 - 1935)
}

