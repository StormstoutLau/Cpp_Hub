// =============================================================================
// 辅助: 从 grunfeld_data.hpp 构造 MatrixXD/VectorXD/cluster_id
// =============================================================================
struct GrunfeldFixture {
    MatrixXD X;
    VectorXD y;
    MatrixXD XtX_inv;
    VectorXD residuals;
    VectorXD beta;
    std::vector<Index> firm_id;
    std::vector<Index> year_id;

    GrunfeldFixture()
        : X(grunfeld::N, grunfeld::K),
          y(grunfeld::N),
          XtX_inv(grunfeld::K, grunfeld::K),
          residuals(grunfeld::N),
          beta(grunfeld::K),
          firm_id(grunfeld::FIRM_ID, grunfeld::FIRM_ID + grunfeld::N),
          year_id(grunfeld::YEAR_ID, grunfeld::YEAR_ID + grunfeld::N) {

        // 填充 X (row-major data -> MatrixXD)
        for (Size i = 0; i < grunfeld::N; ++i) {
            for (Size j = 0; j < grunfeld::K; ++j) {
                X(i, j) = grunfeld::X_DATA[i * grunfeld::K + j];
            }
        }
        // 填充 y
        for (Size i = 0; i < grunfeld::N; ++i) {
            y(i) = grunfeld::Y_DATA[i];
        }

        // OLS: β = (X'X)^{-1} X'y
        const Eigen::MatrixXd XtX = X.eigen().transpose() * X.eigen();
        const Eigen::MatrixXd XtX_inv_eigen = XtX.llt().solve(Eigen::MatrixXd::Identity(
            static_cast<Eigen::Index>(grunfeld::K), static_cast<Eigen::Index>(grunfeld::K)));
        XtX_inv = MatrixXD(XtX_inv_eigen);

        const Eigen::VectorXd Xty = X.eigen().transpose() * y.eigen();
        beta = VectorXD(XtX_inv_eigen * Xty);

        // 残差 u = y - X*β
        residuals = VectorXD(y.eigen() - X.eigen() * beta.eigen());
    }
};

// =============================================================================
// 测试套件: GrunfeldClusterSEIntegrationTest
